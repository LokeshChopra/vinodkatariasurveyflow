create index if not exists idx_survey_photos_survey on public.survey_photos(survey_id);

create table if not exists public.survey_files (
  id text primary key,
  survey_id text not null references public.survey_records(id) on delete cascade,
  file_name text not null,
  file_type text,
  file_size bigint default 0,
