-- SurveyFlow + Supabase complete database/storage setup
-- IMPORTANT: This version intentionally allows anonymous CRUD because the current
-- SurveyFlow app has no login/auth flow. Add Supabase Auth/RLS restrictions before
-- using this with sensitive production data.

create extension if not exists pgcrypto;

create table if not exists public.survey_records (
  id text primary key,
  survey_number text not null unique,
  policy_number text,
  registration_number text,
  document_type text,
  status text,
  confidence numeric,
  record jsonb not null,
  raw_text text default '',
  created_at timestamptz not null,
  updated_at timestamptz not null
);

create index if not exists idx_survey_records_policy_number on public.survey_records(policy_number);
create index if not exists idx_survey_records_registration_number on public.survey_records(registration_number);
create index if not exists idx_survey_records_updated_at on public.survey_records(updated_at desc);
create index if not exists idx_survey_records_record_gin on public.survey_records using gin(record);

create table if not exists public.survey_parts (
  id bigint generated by default as identity primary key,
  survey_id text not null references public.survey_records(id) on delete cascade,
  row_id text not null,
  e_no text,
  parts_description text,
  hsn_code text,
  bill_s_no text,
  remark text,
  estimated numeric default 0,
  glass_second_hand_repair numeric,
  metal_35 numeric,
  non_metal numeric,
  gst_rate numeric default 0,
  selected_for_final boolean default true,
