-- Supabase Storage bucket for PDFs/images/source documents.
insert into storage.buckets (id, name, public)
values ('survey-files', 'survey-files', true)
on conflict (id) do update set public = true;

drop policy if exists survey_files_storage_read on storage.objects;
create policy survey_files_storage_read on storage.objects for select to anon, authenticated
using (bucket_id = 'survey-files');

drop policy if exists survey_files_storage_insert on storage.objects;
create policy survey_files_storage_insert on storage.objects for insert to anon, authenticated
with check (bucket_id = 'survey-files');

drop policy if exists survey_files_storage_update on storage.objects;
create policy survey_files_storage_update on storage.objects for update to anon, authenticated
using (bucket_id = 'survey-files') with check (bucket_id = 'survey-files');

drop policy if exists survey_files_storage_delete on storage.objects;
create policy survey_files_storage_delete on storage.objects for delete to anon, authenticated
using (bucket_id = 'survey-files');

