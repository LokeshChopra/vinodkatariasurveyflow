  selected_for_final boolean default true,
  unique(survey_id, row_id)
);
create index if not exists idx_survey_labour_survey on public.survey_labour(survey_id);

create table if not exists public.survey_invoices (
  id bigint generated by default as identity primary key,
  survey_id text not null references public.survey_records(id) on delete cascade,
