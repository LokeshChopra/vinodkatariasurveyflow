create table if not exists public.survey_photos (
  id bigint generated by default as identity primary key,
  survey_id text not null references public.survey_records(id) on delete cascade,
  photo_id text not null,
  file_name text,
  caption text,
  captured_at text,
  public_url text,
  unique(survey_id, photo_id)
