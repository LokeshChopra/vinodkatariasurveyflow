  public_url text,
  uploaded_at timestamptz not null default now()
);
create index if not exists idx_survey_files_survey on public.survey_files(survey_id);

-- DB-backed sequential reference numbers: SF/SRV/YYYY/MM/0001 ...
create table if not exists public.survey_sequences (
  year_no integer not null,
  month_no integer not null,
  last_number integer not null default 0,
  primary key(year_no, month_no)
);

create or replace function public.generate_survey_number()
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_year integer := extract(year from now())::integer;
  v_month integer := extract(month from now())::integer;
  v_next integer;
begin
  insert into public.survey_sequences(year_no, month_no, last_number)
  values (v_year, v_month, 1)
  on conflict (year_no, month_no)
  do update set last_number = public.survey_sequences.last_number + 1
  returning last_number into v_next;

  return format('SF/SRV/%s/%s/%s', v_year, lpad(v_month::text, 2, '0'), lpad(v_next::text, 4, '0'));
end;
$$;

grant execute on function public.generate_survey_number() to anon, authenticated;

